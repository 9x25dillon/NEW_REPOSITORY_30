// game/lattice.ts — what you can build, and why you cannot build anything else.
//
// The crafting system is a restriction theorem. That is not a conceit: a
// protein is built from L-amino acids, so it is chiral, so it cannot sit in any
// symmetry operation that would hand it its own mirror image. Of the 32
// crystallographic point groups exactly 11 survive that — the enantiomorphic
// ones, which contain only proper rotations — and src/sohncke.ts is already
// built on the fact. So the recipe list below is not a design decision anyone
// made. It is every cell a chiral world permits, and there are eleven.
//
// HOW A GROUP IS BUILT. Each of the 11 is generated by combining rotation axes,
// and each recipe here is that generation written out:
//
//     an n-fold on the principal axis, alone           ->  1  2  3  4  6
//     ...with a 2-fold across it (a girdle)            ->  222  32  422  622
//     ...with a 3-fold down a body diagonal            ->  23   (from a 2-fold)
//                                                          432  (from a 4-fold)
//
// FIVE IS THE WALL. A 5-fold axis generates no lattice — it cannot tile the
// plane, which is the crystallographic restriction theorem and the oldest hard
// no in the subject. A 5-fold motif in this game therefore never crystallises,
// no matter what it is combined with. It is not a bug to be routed around and
// there is no recipe hidden behind it.
//
// THE TWO STATS ARE IN TENSION, AND THE LIBRARY SETS THE RATE. A cell's
// STRUCTURE is its group order — how many operations hold it together. Its
// FREEDOM is the number of independent piezoelectric components neumann.ts
// finds surviving in it — how many distinct ways a field can drive it. Neumann's
// principle makes these pull against each other exactly: 1 has order 1 and 18
// free components, 432 has order 24 and none at all. Nothing balances that
// curve. It is what a projector onto the invariant subspace does.

