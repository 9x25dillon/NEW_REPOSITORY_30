// ── motifs: the things drifting in the medium ───────────────────────────────

/** Where a motif's rotation axis sits relative to the principal one. */
export type Role = "axial" | "girdle" | "diagonal";

export interface Motif {
  id: string;
  label: string;
  role: Role;
  /** Proper rotation order. 5 is included precisely because it is impossible. */
  order: 1 | 2 | 3 | 4 | 5 | 6;
  /** The particle this motif is, acoustically. Its contrast sign decides
   *  whether you gather it at a node or at an antinode, and its radius decides
   *  whether you can gather it at all. */
  particle: Particle;
  /** One line, shown when it is selected. */
  note: string;
}

