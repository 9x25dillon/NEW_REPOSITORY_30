// ── what a cell then is ─────────────────────────────────────────────────────

/** What a cell can be used for. Read off the group, never assigned by hand. */
export type Ability = "thrust" | "weave" | "anchor";

export interface Cell {
  group: PointGroup;
  /** Group order: how many operations hold it together. */
  structure: number;
  /** Independent piezoelectric components: how many ways a field can drive it. */
  freedom: number;
  /** How many Sohncke space groups realise this point group — how many
   *  distinct crystals it could actually be. Flavour, and true. */
  variants: number;
  ability: Ability;
  /** Shown in the inventory. */
  blurb: string;
}

/**
 * The cell a group makes.
 *
 * Every field here is computed. `ability` in particular is not a table of
 * game-design choices — it is three predicates out of pointgroups.ts asked in
 * order, and the interesting one is last: 432 is the single group that is
 * non-centrosymmetric and still not piezoelectric, so it is the single cell
 * with no drivable coefficient at all. gorkov's neighbours call that a famous
 * edge case. Here it is the endgame item.
 */
export function cellFor(hm: string): Cell {
  const g = pointGroup(hm);
  const freedom = independentComponents(hm, "piezoelectric");
  const ability: Ability = isPolar(g) ? "thrust" : isPiezoelectric(g) ? "weave" : "anchor";
  return {
    group: g,
    structure: g.order,
    freedom,
    variants: groupsOfPointGroup(hm).length,
    ability,
    blurb: BLURB[ability],
  };
}

const BLURB: Readonly<Record<Ability, string>> = {
  thrust:
    "POLAR: ONE DIRECTION SURVIVES EVERY OPERATION, SO IT CAN PUSH ALONG IT",
  weave:
    "PIEZOELECTRIC BUT NOT POLAR: IT TURNS YOUR PRESSURE INTO STRUCTURE",
  anchor:
    "ORDER 24 AND NOT ONE DRIVABLE COMPONENT. IT CANNOT BE MOVED, WHICH IS THE POINT",
};

/** The eleven, in build order. */
export const BUILDABLE: readonly string[] = RECIPES.map((r) => r.group);
