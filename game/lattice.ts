// ── the eleven recipes ──────────────────────────────────────────────────────

export interface Recipe {
  /** Motif ids, sorted, that generate the group. */
  parts: readonly string[];
  /** Hermann-Mauguin symbol of what they generate. */
  group: string;
}

/** Every cell a chiral world permits. There is no twelfth. */
export const RECIPES: readonly Recipe[] = [
  { parts: ["a1"], group: "1" },
  { parts: ["a2"], group: "2" },
  { parts: ["a3"], group: "3" },
  { parts: ["a4"], group: "4" },
  { parts: ["a6"], group: "6" },
  { parts: ["a2", "g"], group: "222" },
  { parts: ["a3", "g"], group: "32" },
  { parts: ["a4", "g"], group: "422" },
  { parts: ["a6", "g"], group: "622" },
  { parts: ["a2", "d"], group: "23" },
  { parts: ["a4", "d"], group: "432" },
];

const key = (ids: readonly string[]): string => [...new Set(ids)].sort().join("+");
const BY_PARTS = new Map(RECIPES.map((r) => [key(r.parts), r]));

/** How many motifs must be gathered before a matching set is a crystal rather
 *  than a handful of molecules. A unit cell is not a crystal. */
export const SEED_MASS = 4;

/** Why a set of motifs did not become a cell. */
export type Refusal =
  | "five-fold"       // the crystallographic restriction theorem
  | "two-axes"        // two different principal axes cannot both be principal
  | "no-axis"         // a girdle or a diagonal with nothing to be across
  | "unknown";        // a combination no chiral group is generated by

export interface Assembly {
  /** Every motif in the cluster, including repeats. */
  parts: string[];
  /** The distinct motifs, which are what select the recipe. */
  distinct: string[];
  /** How many motifs are gathered. Mass, not variety. */
  mass: number;
  /** The group these motifs generate, or null if they generate nothing. */
  group: string | null;
  refusal: Refusal | null;
  /** The distinct set is a proper subset of some recipe: worth carrying on. */
  partial: boolean;
  /** Enough of them, and the right ones. This is a cell. */
  crystallises: boolean;
}

/**
 * What a pile of motifs is.
 *
 * Answers four questions at once because the game asks all four every frame: is
 * this a cell yet, could it still become one, has it enough mass, and if it is
 * refused then why exactly. The last matters most — a crafting system that only
 * says NO teaches nothing, and every refusal below has a reason a
 * crystallographer would actually give.
 *
 * VARIETY SELECTS THE GROUP, MASS DECIDES WHETHER IT CRYSTALLISES. One dimer is
 * a molecule with a two-fold axis; four of them stacked on that axis are a
 * crystal of group 2. Adding a fifth changes nothing about which group it is,
 * which is why the recipe is keyed on the distinct set alone.
 */
export function assemble(parts: readonly string[], seed = SEED_MASS): Assembly {
  const all = [...parts].sort();
  const distinct = [...new Set(all)].sort();
  const ms = distinct.map(motif);

  const hit = BY_PARTS.get(key(distinct));
  const enough = all.length >= seed;
  if (hit) {
    return {
      parts: all, distinct, mass: all.length,
      group: hit.group, refusal: null, partial: !enough,
      crystallises: enough,
    };
  }

  const axials = ms.filter((m) => m.role === "axial");
  const partial = RECIPES.some((r) =>
    distinct.length < r.parts.length && distinct.every((id) => r.parts.includes(id)));

  let refusal: Refusal = "unknown";
  if (ms.some((m) => m.order === 5)) refusal = "five-fold";
  else if (axials.length > 1) refusal = "two-axes";
  else if (axials.length === 0 && ms.length > 0) refusal = "no-axis";

  // A five-fold is never partial: nothing it joins can rescue it.
  const fiveFold = ms.some((m) => m.order === 5);
  return {
    parts: all, distinct, mass: all.length,
    group: null,
    refusal: partial && !fiveFold ? null : refusal,
    partial: partial && !fiveFold,
    crystallises: false,
  };
}

/** Whether two clusters are allowed to merge at all. Refused pairs bounce, and
 *  the refusal is what the player is told. */
export function canMerge(a: readonly string[], b: readonly string[]): Assembly {
  return assemble([...a, ...b]);
}

